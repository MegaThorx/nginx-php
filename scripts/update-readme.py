#!/usr/bin/env python3
"""Regenerates the image tables in README.md from the images published on GHCR.

Only the block between the image markers is rewritten. The output contains no
timestamps, so README.md only changes when an image or the set of supported
PHP versions changes.
"""

import datetime
import pathlib
import sys

from common import (
    ENDOFLIFE_URL, IMAGE, LABEL_PREFIX, Registry, env_value, get_json, is_eol, labels, platform_digests, version_key,
)

README = pathlib.Path(__file__).resolve().parent.parent / "README.md"
START = "<!-- images:start -->"
END = "<!-- images:end -->"


def collect(today):
    registry = Registry(IMAGE)
    rows = []
    for entry in get_json(ENDOFLIFE_URL):
        cycle = entry["cycle"]
        if version_key(cycle)[0] < 7:
            continue
        manifest, digest = registry.manifest(cycle)
        if manifest is None:
            continue
        config_digest = platform_digests(manifest).get("amd64", digest) if "manifests" in manifest else digest
        config = registry.config(config_digest)
        rows.append({
            "cycle": cycle,
            "digest": digest,
            "php": env_value(config, "PHP_VERSION"),
            "alpine": labels(config).get(f"{LABEL_PREFIX}alpine.version"),
            "nginx": labels(config).get(f"{LABEL_PREFIX}nginx.version"),
            "eol": entry["eol"],
            "is_eol": is_eol(entry, today),
        })

    shared_tags = ["latest"] + sorted({row["cycle"].split(".")[0] for row in rows}, key=int, reverse=True)
    shared_digests = {tag: registry.digest(tag) for tag in shared_tags}
    for row in rows:
        row["tags"] = [row["cycle"]]
        if row["php"] and registry.digest(row["php"]) == row["digest"]:
            row["tags"].append(row["php"])
        row["tags"] += [tag for tag in shared_tags if shared_digests[tag] == row["digest"]]
    return rows


def render(rows):
    rows = sorted(rows, key=lambda row: version_key(row["cycle"]), reverse=True)
    supported = [row for row in rows if not row["is_eol"]]
    eol = [row for row in rows if row["is_eol"]]

    def cell(value):
        return str(value) if value not in (None, False) else "—"

    lines = [
        START,
        "<!-- Generated by scripts/update-readme.py, do not edit by hand. -->",
        "",
        "### Supported",
        "",
        "| Tags | PHP | Alpine | nginx | Security support until |",
        "|------|-----|--------|-------|------------------------|",
    ]
    for row in supported:
        tags = " ".join(f"`{tag}`" for tag in row["tags"])
        lines.append(f"| {tags} | {cell(row['php'])} | {cell(row['alpine'])} | {cell(row['nginx'])} | {cell(row['eol'])} |")
    if not supported:
        lines.append("| — | | | | |")
    if eol:
        lines += [
            "",
            "### End of life (no longer updated)",
            "",
            "| Tags | PHP | End of life |",
            "|------|-----|-------------|",
        ]
        for row in eol:
            tags = " ".join(f"`{tag}`" for tag in row["tags"])
            lines.append(f"| {tags} | {cell(row['php'])} | {cell(row['eol'])} |")
    lines.append(END)
    return "\n".join(lines)


def replace_block(text, block):
    start, end = text.find(START), text.find(END)
    if start == -1 or end == -1 or end < start:
        raise RuntimeError(f"README.md must contain {START} followed by {END}")
    return text[:start] + block + text[end + len(END):]


def main():
    today = datetime.datetime.now(datetime.timezone.utc).date()
    old = README.read_text()
    new = replace_block(old, render(collect(today)))
    if new == old:
        print("README.md is up to date")
        return
    README.write_text(new)
    print("README.md updated")


if __name__ == "__main__":
    sys.exit(main())
